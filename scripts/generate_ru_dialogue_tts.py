def generate_multi_voice_audio(output_file: str):
    print("🎙️ Инициализация EdgeTTSHelper для русской озвучки с рецензией...")
    helper = EdgeTTSHelper(sample_rate=44100)
    
    output_path = Path(output_file).resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    temp_wav_files = []
    
    with tempfile.TemporaryDirectory() as temp_dir:
        print("\n⏳ Генерация голосовых фрагментов:")
        for idx, seg in enumerate(SEGMENTS):
            seg_file = os.path.join(temp_dir, f"seg_{idx:02d}.wav")
            trimmed_file = os.path.join(temp_dir, f"seg_{idx:02d}_trimmed.wav")
            
            speaker = seg["speaker"]
            voice = seg["voice"]
            rate = seg.get("rate", "+0%")
            pitch = seg.get("pitch", "+0Hz")
            text = seg["text"]
            
            print(f"  [{idx+1}/{len(SEGMENTS)}] 🗣️ {speaker} ({voice}, rate={rate}, pitch={pitch}):")
            print(f"      «{text[:60]}...»")
            
            helper.synthesize_to_wav(text, seg_file, voice=voice, rate=rate, pitch=pitch)
            helper.trim_silence_file(seg_file, trimmed_file, threshold=0.005, pad_ms=60)
            temp_wav_files.append(trimmed_file)
            
        print("\n⏳ Объединение фрагментов с динамическими паузами...")
        all_data = []
        sample_rate = 44100
        
        for idx, path in enumerate(temp_wav_files):
            data, sr = sf.read(path)
            all_data.append(data)
            
            if idx < len(temp_wav_files) - 1:
                if "Закадровый голос" in SEGMENTS[idx+1]["speaker"] or "Цитата" in SEGMENTS[idx+1]["speaker"]:
                    pause_dur = 0.7
                else:
                    pause_dur = 0.45
                
                silence_samples = int(sr * pause_dur)
                all_data.append(np.zeros(silence_samples))
                
        combined = np.concatenate(all_data)
        
        peak = np.max(np.abs(combined))
        if peak > 0:
            combined = combined / peak * 0.95
            
        sf.write(str(output_path), combined, sample_rate)
        print(f"\n🎉 Аудио файл с рецензией успешно сохранен в: {output_path}")

    # Play audio using afplay
    print(f"\n▶️ Воспроизведение полного аудио через afplay: {output_path}")
    try:
        subprocess.run(["afplay", str(output_path)], check=True)
        print("✅ Воспроизведение полностью завершено.")
    except Exception as e:
        print(f"⚠️ Ошибка при воспроизведении файла: {e}")

if __name__ == "__main__":
    out_file = project_root / "audio_output" / "russian_multivoice_narration.wav"
    generate_multi_voice_audio(str(out_file))
